// Private file storage on local disk.
//
// Uploaded bytes are stored under random names in STORAGE_DIR (outside any web root) and can only
// be read through the authenticated /api/files endpoints. To move to object storage (S3, GCS …)
// replace the four functions marked "storage backend" below; the rest of the app only deals with
// File rows.
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { createHash, randomBytes } from 'node:crypto';
import { pipeline } from 'node:stream/promises';
import multer from 'multer';
import { env } from '../config/env.js';
import { prisma } from '../db/prisma.js';
import { AppError, badRequest } from '../lib/errors.js';
import { checkUpload, sanitizeFilename } from '../lib/fileTypes.js';
import { logger } from '../lib/logger.js';

const filesDir = path.join(env.storageDir, 'files');
const tmpDir = path.join(env.storageDir, 'tmp');

export async function ensureStorage() {
  await fsp.mkdir(filesDir, { recursive: true });
  await fsp.mkdir(tmpDir, { recursive: true });
}

// ── storage backend ──────────────────────────────────────────────────────────
function storedPath(storedName) {
  // storedName is generated by us (hex), but resolve defensively anyway.
  if (!/^[a-f0-9]{48}$/.test(storedName)) throw new Error('invalid stored name');
  return path.join(filesDir, storedName.slice(0, 2), storedName);
}

async function moveIntoStore(tmpPath, storedName) {
  const target = storedPath(storedName);
  await fsp.mkdir(path.dirname(target), { recursive: true });
  await fsp.rename(tmpPath, target);
}

export function openFileStream(file, range) {
  return fs.createReadStream(storedPath(file.storedName), range);
}

export async function removeStoredFile(storedName) {
  await fsp.rm(storedPath(storedName), { force: true });
}
// ─────────────────────────────────────────────────────────────────────────────

export async function storedFileExists(file) {
  try {
    await fsp.access(storedPath(file.storedName));
    return true;
  } catch {
    return false;
  }
}

/** Multer instance: streams uploads to a private temp folder with a size cap. */
export const upload = multer({
  storage: multer.diskStorage({
    destination: (req, file, cb) => {
      fsp.mkdir(tmpDir, { recursive: true }).then(() => cb(null, tmpDir), cb);
    },
    filename: (req, file, cb) => cb(null, randomBytes(24).toString('hex')),
  }),
  limits: { fileSize: env.maxUploadBytes, files: 10, fields: 20, fieldSize: 100_000 },
});

async function readHead(filePath, length = 4096) {
  const handle = await fsp.open(filePath, 'r');
  try {
    const buffer = Buffer.alloc(length);
    const { bytesRead } = await handle.read(buffer, 0, length, 0);
    return buffer.subarray(0, bytesRead);
  } finally {
    await handle.close();
  }
}

async function sha256OfFile(filePath) {
  const hash = createHash('sha256');
  await pipeline(fs.createReadStream(filePath), hash);
  return hash.digest('hex');
}

/** multer decodes multipart file names as latin1; browsers send UTF-8. */
function decodeOriginalName(name) {
  try {
    const decoded = Buffer.from(name, 'latin1').toString('utf8');
    return decoded.includes('\ufffd') ? name : decoded;
  } catch {
    return name;
  }
}

export async function discardTempFiles(files) {
  await Promise.all((files ?? []).map((f) => fsp.rm(f.path, { force: true }).catch(() => {})));
}

/**
 * Validate temp uploads and turn them into File rows. If any file is rejected nothing is kept.
 * @param {Express.Multer.File[]} files
 * @param {string} ownerId
 * @param {{ imagesOnly?: boolean }} [options]
 */
export async function persistUploads(files, ownerId, options = {}) {
  if (!files || files.length === 0) throw badRequest('No file was uploaded.', 'NO_FILE');
  const prepared = [];
  try {
    for (const file of files) {
      const originalName = sanitizeFilename(decodeOriginalName(file.originalname));
      const verdict = checkUpload(originalName, await readHead(file.path));
      if (!verdict.ok) throw new AppError(415, 'FILE_TYPE_REJECTED', `${originalName}: ${verdict.reason}`);
      if (options.imagesOnly && !verdict.mime.startsWith('image/')) {
        throw new AppError(415, 'FILE_TYPE_REJECTED', `${originalName}: only images are accepted here.`);
      }
      prepared.push({
        tmpPath: file.path,
        originalName,
        storedName: randomBytes(24).toString('hex'),
        mimeType: verdict.mime,
        extension: verdict.extension,
        sizeBytes: file.size,
        sha256: await sha256OfFile(file.path),
      });
    }
  } catch (err) {
    await discardTempFiles(files);
    throw err;
  }

  const rows = [];
  for (const item of prepared) {
    await moveIntoStore(item.tmpPath, item.storedName);
    rows.push(
      await prisma.file.create({
        data: {
          ownerId,
          originalName: item.originalName,
          storedName: item.storedName,
          mimeType: item.mimeType,
          extension: item.extension,
          sizeBytes: item.sizeBytes,
          sha256: item.sha256,
        },
      }),
    );
  }
  return rows;
}

/** Store bytes produced by the server itself (e.g. an exported document kept as a resource). */
export async function persistBuffer(buffer, { ownerId, originalName }) {
  const name = sanitizeFilename(originalName);
  const verdict = checkUpload(name, buffer.subarray(0, 4096));
  if (!verdict.ok) throw new AppError(415, 'FILE_TYPE_REJECTED', verdict.reason);
  const storedName = randomBytes(24).toString('hex');
  const tmpPath = path.join(tmpDir, storedName);
  await fsp.mkdir(tmpDir, { recursive: true });
  await fsp.writeFile(tmpPath, buffer);
  await moveIntoStore(tmpPath, storedName);
  return prisma.file.create({
    data: {
      ownerId,
      originalName: name,
      storedName,
      mimeType: verdict.mime,
      extension: verdict.extension,
      sizeBytes: buffer.length,
      sha256: createHash('sha256').update(buffer).digest('hex'),
    },
  });
}

export async function readStoredFile(file) {
  return fsp.readFile(storedPath(file.storedName));
}

export const fileSummary = (file) =>
  file
    ? {
        id: file.id,
        name: file.originalName,
        mimeType: file.mimeType,
        extension: file.extension,
        sizeBytes: file.sizeBytes,
        createdAt: file.createdAt,
      }
    : null;

const PARENT_FIELDS = [
  'assignmentId', 'submissionId', 'announcementId', 'messageId', 'threadId', 'replyId', 'studentAnswerId', 'correctionRequestId',
];

const unattachedWhere = Object.fromEntries(PARENT_FIELDS.map((f) => [f, null]));

/**
 * Attach previously uploaded files to a parent record.
 * Only files uploaded by `ownerId` that are not attached to anything yet are accepted, which
 * stops a user from "attaching" (and thereby gaining access to) somebody else's file.
 */
export async function attachFiles(tx, { fileIds, ownerId, field, parentId, max = 10 }) {
  const ids = [...new Set(fileIds ?? [])];
  if (ids.length === 0) return [];
  if (!PARENT_FIELDS.includes(field)) throw new Error(`unknown attachment field ${field}`);
  if (ids.length > max) throw badRequest(`You can attach at most ${max} files.`, 'TOO_MANY_FILES');
  const files = await tx.file.findMany({
    where: { id: { in: ids }, ownerId, deletedAt: null, ...unattachedWhere, avatarOf: null, resources: { none: {} }, aiReferences: { none: {} } },
  });
  if (files.length !== ids.length) {
    throw badRequest('One of the attached files is no longer available. Please upload it again.', 'INVALID_ATTACHMENT');
  }
  await tx.file.updateMany({ where: { id: { in: ids } }, data: { [field]: parentId } });
  return files;
}

/**
 * Make a parent's attachments equal to `fileIds`: detach files that were removed, attach new ones.
 */
export async function syncAttachments(tx, { fileIds, ownerId, field, parentId, max = 10 }) {
  const wanted = [...new Set(fileIds ?? [])];
  if (wanted.length > max) throw badRequest(`You can attach at most ${max} files.`, 'TOO_MANY_FILES');
  const current = await tx.file.findMany({ where: { [field]: parentId, deletedAt: null }, select: { id: true } });
  const currentIds = new Set(current.map((f) => f.id));
  const toDetach = [...currentIds].filter((id) => !wanted.includes(id));
  const toAttach = wanted.filter((id) => !currentIds.has(id));
  if (toDetach.length > 0) {
    await tx.file.updateMany({ where: { id: { in: toDetach } }, data: { [field]: null, deletedAt: new Date() } });
  }
  if (toAttach.length > 0) await attachFiles(tx, { fileIds: toAttach, ownerId, field, parentId, max });
}

/** Delete uploads that were never attached to anything (abandoned forms). Run by the scheduler. */
export async function purgeOrphanFiles(olderThanMs = 24 * 60 * 60 * 1000) {
  const cutoff = new Date(Date.now() - olderThanMs);
  const orphans = await prisma.file.findMany({
    where: {
      createdAt: { lt: cutoff },
      ...unattachedWhere,
      avatarOf: null,
      resources: { none: {} },
      aiReferences: { none: {} },
    },
    take: 200,
  });
  let removed = 0;
  for (const file of orphans) {
    try {
      await prisma.file.delete({ where: { id: file.id } });
      await removeStoredFile(file.storedName);
      removed += 1;
    } catch (err) {
      logger.warn({ err, fileId: file.id }, 'could not purge orphan file');
    }
  }
  // Leftover temp uploads from interrupted requests.
  try {
    for (const name of await fsp.readdir(tmpDir)) {
      const full = path.join(tmpDir, name);
      const stat = await fsp.stat(full);
      if (Date.now() - stat.mtimeMs > 60 * 60 * 1000) await fsp.rm(full, { force: true });
    }
  } catch {
    // temp dir may not exist yet
  }
  return removed;
}
